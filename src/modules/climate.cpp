/**
 * @file climate.cpp
 * @brief Реализация модуля эмуляции климатических данных.
 * 
 * Содержит реализацию методов класса Climate для генерации и публикации
 * данных о состоянии климатической системы автомобиля. Данные включают
 * температуру внутри и снаружи, давление в шинах и уровень омывателя.
 */

#include "climate.h"
#include "core/message.h"
#include "core/logging.h"

/**
 * @brief Инициализация модуля Climate.
 * 
 * Выполняет начальную настройку модуля при старте системы:
 * - Обнуляет структуру данных с помощью memset
 * - Устанавливает версию пакета данных
 * - Задает начальные значения температур
 * 
 * @return true — инициализация всегда успешна
 */
bool Climate::onInit() {
    memset(&pack, 0, sizeof(pack));
    pack.version = 1;
    pack.interior_temp = 22; pack.exterior_temp = 15;
    return true;
}

/**
 * @brief Периодическая обработка и генерация данных.
 * 
 * Метод вызывается регулярно из основного цикла приложения. Выполняет:
 * - Проверку времени с последней публикации (раз в секунду)
 * - Генерацию новых случайных значений для всех параметров
 * - Публикацию обновленных данных в топик Topic::SERVICE
 * 
 * Генерируемые данные:
 * - Внутренняя температура: случайное значение от 20.0 до 25.0°C
 * - Внешняя температура: случайное значение от 10.0 до 18.0°C
 * - Давление в шинах: 5% вероятность низкого давления (true)
 * - Уровень омывателя: 3% вероятность низкого уровня (true)
 */
void Climate::onProcess() {
    unsigned long now = millis();
    if (now - lastPublish >= 1000) {
        lastPublish = now;
        pack.interior_temp = 20 + random(0,50)/10.0f;
        pack.exterior_temp = 10 + random(0,80)/10.0f;
        pack.tire_pressure = random(0,100) < 5;
        pack.washer_level = random(0,100) < 3;
        publish(Topic::SERVICE, &pack, sizeof(pack));
    }
}