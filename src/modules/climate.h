/**
 * @file climate.h
 * @brief Модуль эмуляции данных климатической системы.
 * 
 * Класс Climate генерирует и публикует данные о состоянии климатической системы,
 * включая температуру внутри и снаружи автомобиля, давление в шинах и уровень
 * омывателя. Данные публикуются в топик Topic::SERVICE каждую секунду.
 * 
 * Основные функции:
 * - Генерация случайных значений температур
 * - Эмуляция низкого давления в шинах (5% вероятность)
 * - Эмуляция низкого уровня омывателя (3% вероятность)
 * - Периодическая публикация данных в шину сообщений
 */

#ifndef CLIMATE_H
#define CLIMATE_H

#include "core/module.h"
#include "core/packets.h"

/**
 * @class Climate
 * @brief Модуль эмуляции климатических данных.
 * 
 * Генерирует и публикует данные о состоянии климатической системы
 * для отображения на приборной панели. Используется для тестирования
 * интерфейса отображения без реальных датчиков.
 */
class Climate : public Module {
public:
    /**
     * @brief Конструктор модуля.
     * 
     * Устанавливает имя модуля как "Climate" для логирования.
     */
    Climate() : Module("Climate") {}

protected:
    /**
     * @brief Инициализация модуля.
     * 
     * Инициализирует данные климатической системы с начальными значениями:
     * - Внутренняя температура: 22°C
     * - Внешняя температура: 15°C
     * 
     * @return true — всегда успешна
     */
    bool onInit() override;

    /**
     * @brief Периодическая обработка.
     * 
     * Каждую секунду генерирует новые случайные значения для:
     * - Внутренней температуры (20-25°C)
     * - Внешней температуры (10-18°C)
     * - Давления в шинах (5% вероятность низкого давления)
     * - Уровня омывателя (3% вероятность низкого уровня)
     * 
     * Сгенерированные данные публикуются в топик Topic::SERVICE.
     */
    void onProcess() override;

private:
    /**
     * @brief Структура данных климатической системы.
     * 
     * Содержит все данные, связанные с климатом и сервисными системами,
     * которые публикуются в шину сообщений.
     */
    ClimatePack pack;

    /**
     * @brief Время последней публикации данных.
     * 
     * Используется для управления периодичностью публикации (раз в секунду).
     */
    unsigned long lastPublish = 0;
};

#endif