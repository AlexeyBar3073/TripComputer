/**
 * @file transport.cpp
 * @brief Реализация модуля Bluetooth-транспорта.
 * 
 * Содержит реализацию методов класса Transport для управления
 * Bluetooth-соединением, приема и передачи данных. Обеспечивает
 * двунаправленную связь между устройством и внешним клиентом.
 */

#include <Arduino.h>
#include "transport.h"
#include "core/message.h"
#include "core/logging.h"
#include "core/command_msg.h"

/**
 * @brief Инициализация модуля Bluetooth-транспорта.
 * 
 * Выполняет начальную настройку модуля при старте системы:
 * - Настраивает GPIO для светодиода подключения как выход
 * - Устанавливает начальное состояние светодиода (выключен)
 * - Инициализирует Bluetooth-серийный порт с именем "TripComputer"
 * - Подписывается на топик Topic::PROTOCOL для отправки исходящих данных
 * - Инициализирует буфер приема (обнуление и установка длины)
 * 
 * При неудачной инициализации Bluetooth записывает ошибку в лог
 * и возвращает false.
 * 
 * @return true при успешной инициализации, false при ошибке инициализации Bluetooth
 */
bool Transport::onInit() {
    // Настраиваем GPIO пин светодиода подключения как выход
    pinMode(LED_BUILTIN, OUTPUT);
    
    // Устанавливаем начальное состояние светодиода - выключен
    digitalWrite(LED_BUILTIN, LOW);
    
    // Инициализируем Bluetooth-серийный порт с именем "TripComputer"
    // Это имя будет отображаться при поиске Bluetooth-устройств
    if (!btSerial.begin("TripComputer")) {
        // Если инициализация Bluetooth не удалась, записываем ошибку в лог
        LOG_ERROR(name, "BT init failed");
        // Возвращаем false для сигнализации неудачной инициализации
        return false;
    }
    
    // При успешной инициализации записываем информационное сообщение в лог
    LOG_INFO(name, "BT started");
    
    // Подписываемся на топик Topic::PROTOCOL для получения исходящих сообщений
    // Указываем размер буфера 512 байта, что достаточно для полного JSON-сообщения
    subscribeNew(Topic::PROTOCOL, 512);
    
    // Инициализируем длину буфера приема нулем
    rxLen = 0;
    
    // Обнуляем буфер приема, очищая его содержимое
    memset(rxBuffer, 0, RX_BUF_SIZE);
    
    // Возвращаем true, сигнализируя об успешной инициализации модуля
    return true;
}

/**
 * @brief Обработка исходящих данных.
 * 
 * Вызывается при получении данных в топик Topic::PROTOCOL,
 * на который модуль подписан. Передает содержимое сообщения
 * в Bluetooth-соединение посимвольно.
 * 
 * Формат передачи:
 * - Сначала передаются все байты сообщения
 * - Затем передается символ новой строки ('\n')
 * 
 * Используется для отправки ответов, телеметрии и уведомлений
 * клиентскому приложению.
 * 
 * @param topic Идентификатор топика, из которого получены данные
 * @param data Указатель на данные (строка)
 */
void Transport::onData(uint16_t topic, const void* data) {
    // Проверяем, является ли топик Topic::PROTOCOL источником данных
    // Это обеспечивает фильтрацию сообщений и обработку только нужных данных
    if (topic == Topic::PROTOCOL) {
        // Преобразуем указатель на данные в строку (char*)
        // Это позволяет работать с данными как с текстом
        const char* msg = (const char*)data;
        
        // Записываем содержимое сообщения в Bluetooth-соединение
        // Передаем указатель на данные и их длину
        btSerial.write((uint8_t*)msg, strlen(msg));
        
        // Добавляем символ новой строки в конец сообщения
        // Это необходимо для корректного разделения сообщений на стороне получателя
        // и обеспечивает совместимость с текстовыми протоколами
        btSerial.write('\n');
    }
}

/**
 * @brief Периодическая обработка фоновых задач.
 * 
 * Вызывается регулярно из основного цикла приложения для выполнения
 * фоновых операций, необходимых для поддержания соединения:
 * - Проверка состояния подключения (checkConnection)
 * - Чтение входящих данных (readBluetooth)
 * 
 * Не имеет возвратного значения, так как ошибки обрабатываются
 * внутри вызываемых методов и записываются в лог.
 */
void Transport::onProcess() {
    // Проверяем текущее состояние Bluetooth-подключения
    // Метод проверяет наличие подключенного клиента и обновляет состояние
    // светодиода, записывает лог и публикует команду о состоянии подключения
    checkConnection();
    
    // Читаем входящие данные из Bluetooth-соединения
    // Метод посимвольно считывает данные в буфер и при получении полного
    // сообщения (до символа '\n') передает его на обработку в processLine()
    readBluetooth();
}

/**
 * @brief Проверка состояния Bluetooth-подключения.
 * 
 * Проверяет, подключен ли клиент к Bluetooth-серверу и изменилось ли
 * состояние подключения с момента последней проверки. При изменении состояния:
 * - Обновляет состояние светодиода подключения
 * - Записывает информацию о подключении в лог
 * - Публикует команду CMD_TRANSPORT_STATUS в топик Topic::SYSTEM
 *   для уведомления других модулей о состоянии соединения
 * 
 * Метод обеспечивает синхронизацию состояния подключения между
 * физическим устройством, пользовательским интерфейсом и логикой приложения.
 */
void Transport::checkConnection() {
    // Проверяем наличие подключенного клиента к Bluetooth-серверу
    // Метод hasClient() возвращает true, если есть активное соединение
    bool now = btSerial.hasClient();
    
    // Проверяем, изменилось ли состояние подключения по сравнению с предыдущей проверкой
    // Это позволяет выполнять действия только при изменении состояния (подключение/отключение)
    if (now != connected) {
        // Обновляем внутреннее состояние подключения
        connected = now;
        
        // Устанавливаем состояние светодиода подключения в соответствии с состоянием соединения
        // Если подключен - светодиод включен (HIGH), если нет - выключен (LOW)
        digitalWrite(LED_BUILTIN, connected ? HIGH : LOW);
        
        // Записываем информацию о состоянии подключения в системный лог
        // Это помогает при отладке и мониторинге состояния Bluetooth
        LOG_INFO(name, "BT %s", connected ? "CONNECTED" : "DISCONNECTED");
        
        // Создаем команду с информацией о состоянии подключения
        // Команда содержит код CMD_TRANSPORT_STATUS и значение 1.0f (подключен) или 0.0f (отключен)
        CommandMsg cmd = {CMD_TRANSPORT_STATUS, connected ? 1.0f : 0.0f};
        
        // Публикуем команду в топик Topic::SYSTEM
        // Это позволяет другим модулям системы реагировать на изменение состояния подключения
        // Например, модуль UI может обновить отображение статуса подключения
        publish(Topic::SYSTEM, &cmd, sizeof(cmd));
    }
}

/**
 * @brief Чтение данных из Bluetooth-соединения.
 * 
 * Проверяет наличие входящих данных и посимвольно считывает их
 * в буфер rxBuffer. Обрабатывает данные по следующему алгоритму:
 * - Игнорирует символы возврата каретки ('\r')
 * - Добавляет все остальные символы в буфер
 * - При получении символа новой строки ('\n') обрабатывает полное сообщение
 * - При переполнении буфера записывает ошибку в лог и сбрасывает буфер
 * 
 * Метод обеспечивает надежный прием сообщений, разделяемых символом '\n',
 * и защиту от переполнения буфера.
 */
void Transport::readBluetooth() {
    // Проверяем, есть ли активное подключение
    // Если нет подключенного клиента, выходим из функции
    // Это предотвращает попытки чтения данных без подключения
    if (!connected) return;
    
    // Цикл чтения доступных данных из Bluetooth-порта
    // Условия продолжения цикла:
    // - Есть доступные для чтения данные (btSerial.available())
    // - Длина буфера приема меньше максимального размера минус 1 (rxLen < RX_BUF_SIZE - 1)
    // Минус 1 оставляет место для нулевого символа завершения строки
    while (btSerial.available() && rxLen < RX_BUF_SIZE - 1) {
        // Считываем один байт из Bluetooth-порта
        char c = btSerial.read();
        
        // Игнорируем символ возврата каретки ('\r')
        // Это необходимо для правильной обработки окончания строки,
        // так как различные системы используют разные комбинации символов
        // для обозначения новой строки (\n, \r\n, \r)
        if (c == '\r') continue;
        
        // Добавляем считанный символ в буфер приема
        // Увеличиваем счетчик длины буфера после добавления символа
        rxBuffer[rxLen++] = c;
        
        // Проверяем, является ли символ концом строки ('\n')
        // Это определяет момент завершения полного сообщения
        if (c == '\n') {
            // Заменяем символ новой строки на нулевой символ для завершения строки
            // Это позволяет обрабатывать сообщение как C-строку
            rxBuffer[rxLen - 1] = '\0';
            
            // Уменьшаем счетчик длины буфера, так как символ '\n' заменен на '\0'
            rxLen--;
            
            // Проверяем, что в буфере есть данные для обработки
            // Это предотвращает обработку пустых сообщений
            if (rxLen > 0) processLine();
            
            // Сбрасываем счетчик длины буфера для приема нового сообщения
            rxLen = 0;
        }
        
        // Проверяем переполнение буфера приема
        // Если длина буфера достигла максимального размера минус 1
        if (rxLen >= RX_BUF_SIZE - 1) {
            // Записываем ошибку в системный лог
            // Это помогает при отладке проблемы с переполнением буфера
            LOG_ERROR(name, "RX overflow");
            
            // Сбрасываем счетчик длины буфера для предотвращения дальнейших проблем
            rxLen = 0;
        }
    }
}

/**
 * @brief Обработка полного принятого сообщения.
 * 
 * Вызывается после получения полного сообщения (до символа '\n').
 * Публикует содержимое сообщения в топик Topic::TRANSPORT для дальнейшей
 * обработки другими модулями системы (например, Protocol).
 * 
 * Длина передаваемых данных включает завершающий нулевой байт,
 * чтобы обеспечить корректную обработку строки в принимающем модуле.
 */
void Transport::processLine() {
    // Публикуем содержимое принятого сообщения в топик Topic::TRANSPORT
    // Это позволяет другим модулям системы (например, Protocol) получить и обработать сообщение
    publish(Topic::TRANSPORT, rxBuffer, strlen(rxBuffer) + 1);
}