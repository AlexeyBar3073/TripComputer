/**
 * @file transport.h
 * @brief Модуль управления Bluetooth-соединением.
 * 
 * Класс Transport обеспечивает двунаправленную связь по Bluetooth с внешними
 * устройствами (смартфон, компьютер). Отвечает за:
 * - Установление и отслеживание соединения
 * - Прием данных от подключенного устройства
 * - Передачу данных в подключенное устройство
 * - Преобразование данных между внутренними топиками и Bluetooth-протоколом
 * 
 * Использует класс BluetoothSerial из Arduino-ESP32 для реализации SPP-протокола.
 * Управляет светодиодом подключения (LED_BUILTIN).
 */

#ifndef TRANSPORT_H
#define TRANSPORT_H

#include "core/module.h"
#include <BluetoothSerial.h>

/**
 * @class Transport
 * @brief Модуль Bluetooth-транспорта для обмена данными.
 * 
 * Реализует двунаправленный обмен данными по Bluetooth. Принимает команды
 * и данные от подключенного устройства и передает ответы и телеметрию обратно.
 * Управляет состоянием соединения и сигнализирует о нем через светодиод.
 */
class Transport : public Module {
public:
    /**
     * @brief Конструктор модуля.
     * 
     * Инициализирует базовый класс с именем "Transport" и устанавливает
     * начальные значения для переменных состояния.
     */
    Transport() : Module("Transport"), connected(false), rxLen(0) {}

protected:
    /**
     * @brief Инициализация модуля Bluetooth.
     * 
     * Выполняет начальную настройку:
     * - Настраивает GPIO для светодиода подключения
     * - Инициализирует Bluetooth-серию с именем "TripComputer"
     * - Подписывается на топик Topic::PROTOCOL для отправки данных
     * - Инициализирует буфер приема
     * 
     * @return true при успешной инициализации Bluetooth, false при ошибке
     */
    bool onInit() override;

    /**
     * @brief Периодическая обработка соединения.
     * 
     * Вызывается регулярно для выполнения фоновых задач:
     * - Проверка состояния подключения
     * - Чтение данных из Bluetooth
     */
    void onProcess() override;

    /**
     * @brief Обработка входящих данных.
     * 
     * Вызывается при получении данных в топик, на который модуль подписан.
     * В данном случае обрабатывает данные из топика Topic::PROTOCOL и
     * пересылает их в Bluetooth-соединение.
     * 
     * @param topic Идентификатор топика, из которого получены данные
     * @param data Указатель на данные
     */
    void onData(uint16_t topic, const void* data) override;

private:
    /**
     * @brief Экземпляр Bluetooth-серии для SPP-соединения.
     * 
     * Предоставляет интерфейс для работы с Bluetooth Serial Protocol.
     */
    BluetoothSerial btSerial;

    /**
     * @brief Флаг текущего состояния подключения.
     * 
     * true - есть подключенный клиент, false - нет подключения.
     */
    bool connected;

    /**
     * @brief Максимальный размер буфера приема.
     * 
     * Определяет максимальное количество байт, которые могут быть приняты
     * за одну сессию. Достаточно для полного JSON-сообщения.
     */
    static constexpr size_t RX_BUF_SIZE = 512;

    /**
     * @brief Буфер для приема данных по Bluetooth.
     * 
     * Хранит входящие байты до обработки полного сообщения.
     */
    char rxBuffer[RX_BUF_SIZE];


    /**
     * @brief Текущая длина данных в буфере приема.
     * 
     * Указывает, сколько байт в данный момент находится в rxBuffer.
     */
    uint16_t rxLen;

    /**
     * @brief Проверка состояния подключения.
     * 
     * Проверяет, изменилось ли состояние подключения по сравнению
     * с предыдущей проверкой. При изменении состояния:
     * - Обновляет светодиод подключения
     * - Записывает состояние в лог
     * - Публикует команду CMD_TRANSPORT_STATUS в шину сообщений
     */
    void checkConnection();

    /**
     * @brief Чтение данных из Bluetooth.
     * 
     * Проверяет наличие входящих данных и посимвольно считывает их
     * в буфер rxBuffer. При получении символа конца строки ('\n')
     * вызывает processLine() для обработки полного сообщения.
     * Обрабатывает переполнение буфера.
     */
    void readBluetooth();

    /**
     * @brief Обработка полного принятого сообщения.
     * 
     * Вызывается после получения полного сообщения (до '\n').
     * Публикует содержимое сообщения в топик Topic::TRANSPORT
     * для дальнейшей обработки другими модулями.
     */
    void processLine();
};

#endif